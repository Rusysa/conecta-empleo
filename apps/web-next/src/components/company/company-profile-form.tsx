"use client"

import Link from "next/link"
import { Controller, useForm, useWatch } from "react-hook-form"
import { zodResolver } from "@hookform/resolvers/zod"
import { ExternalLink, Loader2 } from "lucide-react"
import { toast } from "sonner"

import { Button } from "@/components/ui/button"
import { Field, FieldDescription, FieldError, FieldGroup, FieldLabel } from "@/components/ui/field"
import { Input } from "@/components/ui/input"
import { Textarea } from "@/components/ui/textarea"
import { LogoUpload } from "@/components/company/logo-upload"
import { companyProfileSchema, slugify, type CompanyProfileInput } from "@/lib/validations/company"

export function CompanyProfileForm({
  defaultValues,
  currentSlug,
  logoUrl,
}: {
  defaultValues: CompanyProfileInput
  currentSlug: string | null
  logoUrl: string | null
}) {
  const form = useForm<CompanyProfileInput>({
    resolver: zodResolver(companyProfileSchema),
    defaultValues,
  })
  const name = useWatch({ control: form.control, name: "name" })
  // The slug is generated by updateCompanyProfile on the server; this is just a preview.
  const slugPreview = currentSlug ?? slugify(name)

  async function onSubmit(values: CompanyProfileInput) {
    // TODO(backend): updateCompanyProfile(values) Server Action (generates a unique slug).
    await new Promise((r) => setTimeout(r, 600))
    console.info("updateCompanyProfile (mock)", values)
    form.reset(values)
    toast.success("Perfil de empresa guardado")
  }

  return (
    <form onSubmit={form.handleSubmit(onSubmit)} noValidate>
      <FieldGroup>
        <div className="rounded-[20px] border border-border bg-secondary p-5 text-secondary-foreground">
          <LogoUpload name={name} logoUrl={logoUrl} />
        </div>

        <Controller
          name="name"
          control={form.control}
          render={({ field, fieldState }) => (
            <Field data-invalid={fieldState.invalid}>
              <FieldLabel htmlFor="name">Nombre de la empresa</FieldLabel>
              <Input
                {...field}
                id="name"
                autoComplete="organization"
                aria-invalid={fieldState.invalid}
              />
              {slugPreview && (
                <FieldDescription>
                  Tu página pública:{" "}
                  <span className="font-mono text-xs">/empresas/{slugPreview}</span>
                </FieldDescription>
              )}
              {fieldState.invalid && <FieldError errors={[fieldState.error]} />}
            </Field>
          )}
        />
        <Controller
          name="description"
          control={form.control}
          render={({ field, fieldState }) => (
            <Field data-invalid={fieldState.invalid}>
              <FieldLabel htmlFor="description">Descripción (opcional)</FieldLabel>
              <Textarea
                {...field}
                id="description"
                rows={4}
                placeholder="¿A qué se dedica tu empresa? ¿Por qué es un buen lugar para trabajar?"
                aria-invalid={fieldState.invalid}
              />
              {fieldState.invalid && <FieldError errors={[fieldState.error]} />}
            </Field>
          )}
        />
        <div className="grid gap-6 sm:grid-cols-2">
          <Controller
            name="location"
            control={form.control}
            render={({ field, fieldState }) => (
              <Field data-invalid={fieldState.invalid}>
                <FieldLabel htmlFor="location">Ubicación (opcional)</FieldLabel>
                <Input
                  {...field}
                  id="location"
                  placeholder="Ej. Monterrey, N.L."
                  aria-invalid={fieldState.invalid}
                />
                {fieldState.invalid && <FieldError errors={[fieldState.error]} />}
              </Field>
            )}
          />
          <Controller
            name="website"
            control={form.control}
            render={({ field, fieldState }) => (
              <Field data-invalid={fieldState.invalid}>
                <FieldLabel htmlFor="website">Sitio web (opcional)</FieldLabel>
                <Input
                  {...field}
                  id="website"
                  type="url"
                  inputMode="url"
                  placeholder="https://tuempresa.com"
                  aria-invalid={fieldState.invalid}
                />
                {fieldState.invalid && <FieldError errors={[fieldState.error]} />}
              </Field>
            )}
          />
        </div>

        <div className="flex flex-wrap gap-2">
          <Button
            type="submit"
            className="h-11 px-6"
            disabled={form.formState.isSubmitting || !form.formState.isDirty}
          >
            {form.formState.isSubmitting && <Loader2 className="animate-spin" />}
            Guardar cambios
          </Button>
          {currentSlug && (
            <Button variant="outline" className="h-11 px-6" asChild>
              <Link href={`/empresas/${currentSlug}`} target="_blank">
                Ver página pública <ExternalLink />
              </Link>
            </Button>
          )}
        </div>
      </FieldGroup>
    </form>
  )
}
